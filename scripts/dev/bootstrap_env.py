"""Write local-only development environment files with fresh random passwords.

  deploy/dev/.env   compose variables for the disposable PostgreSQL
  apps/api/.env     API settings pointing at that database (127.0.0.1:55432)

Both are git-ignored. Existing files are kept unless --force is given (a running database keeps the
passwords it was created with). Nothing here can reach a non-local database.
"""
import secrets
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEV_ENV = ROOT / "deploy" / "dev" / ".env"
API_ENV = ROOT / "apps" / "api" / ".env"


def pw() -> str:
    return secrets.token_urlsafe(32)


def main() -> int:
    force = "--force" in sys.argv
    if DEV_ENV.exists() and API_ENV.exists() and not force:
        print("dev env files exist; keeping them (use --force to regenerate, then recreate the database)")
        return 0
    su, owner, app = pw(), pw(), pw()
    DEV_ENV.write_text(
        "# Local disposable database only. Generated by scripts/dev/bootstrap_env.py.\n"
        f"NOVRSOC_DEV_PG_SUPERUSER_PASSWORD={su}\n"
        f"NOVRSOC_DEV_OWNER_PASSWORD={owner}\n"
        f"NOVRSOC_DEV_APP_PASSWORD={app}\n",
        encoding="utf-8",
    )
    API_ENV.write_text(
        "# Local development only. Generated by scripts/dev/bootstrap_env.py.\n"
        "NOVRSOC_ENV=development\n"
        f"NOVRSOC_DATABASE_URL=postgresql+psycopg://novrsoc_app:{app}@127.0.0.1:55432/novrsoc_v2_dev\n"
        f"NOVRSOC_MIGRATION_DATABASE_URL=postgresql+psycopg://novrsoc_owner:{owner}@127.0.0.1:55432/novrsoc_v2_dev\n"
        f"NOVRSOC_TEST_ADMIN_DATABASE_URL=postgresql+psycopg://postgres:{su}@127.0.0.1:55432/postgres\n"
        "NOVRSOC_SESSION_COOKIE_SECURE=false\n",
        encoding="utf-8",
    )
    print(f"wrote {DEV_ENV.relative_to(ROOT)} and {API_ENV.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
