"""Derive apps/api/requirements.runtime.lock from the tested apps/api/requirements.lock.

The runtime lock holds exactly the packages the API, migrations, NHAI worker and backups need at run time on Linux
(the dependency closure of the [project] dependencies in apps/api/pyproject.toml), at the SAME versions as the tested
lock. Test-only packages (pytest, schema validators) stay out of production images.

  python scripts/release/runtime_lock.py           # write
  python scripts/release/runtime_lock.py --check   # CI: fail if the file is not current

Run it with the API virtualenv (it reads installed package metadata to compute the closure).
"""
from __future__ import annotations

import re
import sys
import tomllib
from importlib import metadata
from pathlib import Path

from packaging.markers import default_environment
from packaging.requirements import Requirement

ROOT = Path(__file__).resolve().parents[2]
LOCK = ROOT / "apps" / "api" / "requirements.lock"
OUT = ROOT / "apps" / "api" / "requirements.runtime.lock"
PYPROJECT = ROOT / "apps" / "api" / "pyproject.toml"
# The production images run on Linux (python:3.12-slim); evaluate environment markers for that platform.
LINUX = {**default_environment(), "sys_platform": "linux", "platform_system": "Linux", "os_name": "posix",
         "python_version": "3.12", "implementation_name": "cpython"}
# Linux-only optional accelerators that the tested lock (resolved on the development host) does not contain. They are
# left out on purpose: production runs the tested set, and uvicorn falls back to the standard asyncio event loop.
NOT_IN_TESTED_LOCK = {"uvloop": "uvicorn[standard] accelerator; the asyncio event loop is used instead"}


def norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def closure(roots: list[Requirement]) -> set[str]:
    seen: set[str] = set()
    todo = [(r, "") for r in roots]
    while todo:
        req, extra = todo.pop()
        if req.marker and not req.marker.evaluate({**LINUX, "extra": extra}):
            continue
        name = norm(req.name)
        if name in NOT_IN_TESTED_LOCK:
            continue
        key =f"{name}[{','.join(sorted(req.extras))}]"
        if key in seen:
            continue
        seen.add(key)
        try:
            dist = metadata.distribution(req.name)
        except metadata.PackageNotFoundError:
            raise SystemExit(f"{req.name} is not installed in this environment (use the API virtualenv)")
        for dep in dist.requires or []:
            d = Requirement(dep)
            if d.marker is None:
                todo.append((d, ""))
            else:
                # a dependency guarded by an extra applies only when that extra was requested
                for e in [""] + sorted(req.extras):
                    if d.marker.evaluate({**LINUX, "extra": e}):
                        todo.append((d, e))
                        break
    return {k.split("[")[0] for k in seen}


def render() -> str:
    roots = [Requirement(d) for d in tomllib.loads(PYPROJECT.read_text(encoding="utf-8"))["project"]["dependencies"]]
    roots.append(Requirement("novrsoc-contracts"))  # installed from packages/contracts in the image
    needed = closure(roots) - {"novrsoc-contracts"}
    pins = {}
    for line in LOCK.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line and not line.startswith("#"):
            name, _, ver = line.partition("==")
            pins[norm(name)] = line
    missing = sorted(n for n in needed if n not in pins)
    if missing:
        raise SystemExit(f"runtime dependencies missing from requirements.lock: {', '.join(missing)}")
    body = "\n".join(pins[n] for n in sorted(needed))
    return ("# GENERATED by scripts/release/runtime_lock.py from requirements.lock (same versions). Do not edit.\n"
            "# Runtime closure of apps/api/pyproject.toml [project] dependencies on Linux; installed with --no-deps.\n"
            + "".join(f"# Not installed: {k} ({v})\n" for k, v in sorted(NOT_IN_TESTED_LOCK.items()))
            + f"{body}\n")


def main() -> int:
    text = render()
    count = sum(1 for x in text.splitlines() if x and not x.startswith("#"))
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("requirements.runtime.lock is not current: run python scripts/release/runtime_lock.py", file=sys.stderr)
            return 1
        print(f"requirements.runtime.lock current ({count} packages)")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({count} packages)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
